import pytest

from tdnet_edge.keywords import match_keywords


@pytest.mark.parametrize(
    "title,expected",
    [
        ("〇〇事業からの撤退に関するお知らせ", ("事業撤退",)),
        ("ＡＢＣ事業からの撤退について", ("事業撤退",)),  # 全角英字
        ("事業譲渡に関するお知らせ", ("事業譲渡",)),
        ("事業の一部譲渡に関するお知らせ", ("事業譲渡",)),
        ("事業譲受に関するお知らせ", ()),
        ("譲渡制限付株式報酬としての新株式発行に関するお知らせ", ()),
        ("不採算店舗の閉鎖に関するお知らせ", ("店舗閉鎖",)),
        ("閉店に関するお知らせ", ("店舗閉鎖",)),
        ("連結子会社の解散及び特別損失の計上に関するお知らせ", ("子会社の解散", "特別損失")),
        ("海外子会社の解散及び清算に関するお知らせ", ("子会社の解散",)),
        ("特別利益の計上に関するお知らせ", ()),
        ("減損損失の計上に関するお知らせ", ("減損",)),
        ("固定資産の減損損失及び特別損失の計上並びに業績予想の修正に関するお知らせ", ("特別損失", "減損")),
        ("事業構造改革の実施に関するお知らせ", ("構造改革",)),
        ("製品価格改定のお知らせ", ("価格改定",)),
        ("一部商品の価格の改定について", ("価格改定",)),
        ("電気料金の改定について", ("価格改定",)),
        ("２０２５年３月期 決算短信〔日本基準〕（連結）", ()),
        # 除外（初回の悪材料開示ではない）
        ("（訂正）「減損損失の計上に関するお知らせ」の一部訂正について", ()),
        ("（開示事項の経過）連結子会社の解散に関するお知らせ", ()),
        ("連結子会社の清算結了に関するお知らせ", ()),
        ("事業譲渡の中止に関するお知らせ", ()),
        ("店舗閉鎖の延期について", ()),
        ("", ()),
    ],
)
def test_match_keywords(title, expected):
    assert match_keywords(title) == expected


def test_exclusion_can_be_disabled_for_counting():
    assert match_keywords("（訂正）減損損失の計上に関するお知らせ", apply_exclusions=False) == ("減損",)
